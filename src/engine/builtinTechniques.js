// 内置技法卡。离线可用，被创作/精修 AI 检索引用，也可一键套用到所选镜头。
// 约定：id 前缀 bt_；builtin:true；apply.ops 的 target 统一 { mode:'selected', indices:[], ids:[] }。

const sel = () => ({ mode: 'selected', indices: [], ids: [] });
const op = (type, params = {}) => ({ type, target: sel(), ...params });

const look = (name, strength = 1) => op('setLook', { look: name, lookStrength: strength });
const color = (c, relative = false) => op('setColor', { color: c, relative });
const motion = (preset, intensity = 0.5) => op('setMotion', { preset, intensity });
const transition = (type, duration = 0.5) => op('setTransition', { transition: { type, duration } });
const fx = (f, relative = false) => op('setFx', { fx: f, relative });
const pacing = (p) => op('applyPacing', { pacing: p });
const speed = (s) => op('setSpeed', { speed: s });
const caption = (c) => op('setCaption', { caption: c });
const volume = (v) => op('setVolume', v);

function card(id, category, title, summary, steps, whenToUse, tags, ops = null, note = '') {
  return {
    id: `bt_${id}`,
    category,
    title,
    summary,
    steps,
    whenToUse,
    tags,
    builtin: true,
    apply: ops && ops.length ? { ops, note: note || '套用到所选镜头，可随时撤销' } : null,
  };
}

