let currentLocale = 'zh-CN';
const listeners = new Set();

/** Map locale strings ('en', 'en-US', 'en-GB', etc.) to a supported locale; defaults to 'zh-CN'. */
export function normalizeLocale(v) {
  if (typeof v !== 'string') return 'zh-CN';
  const s = v.trim().toLowerCase().replace(/_/g, '-');
  if (s === 'en' || s.startsWith('en-')) return 'en-US';
  return 'zh-CN';
}

export function getLocale() {
  return currentLocale;
}

export function setLocale(locale) {
  const next = normalizeLocale(locale);
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = next;
  }
  if (next === currentLocale) return next;
  currentLocale = next;
  for (const fn of Array.from(listeners)) {
    try { fn(currentLocale); } catch { /* subscriber errors do not affect others */ }
  }
  return currentLocale;
}

export function subscribeLocale(fn) {
  if (typeof fn !== 'function') return () => {};
  listeners.add(fn);
  return () => { listeners.delete(fn); };
}

/** Resolve dictionary key with fallback to zh-CN and clean {{varName}} interpolation. */
export function t(key, vars = null, localeOverride = null) {
  const loc = localeOverride ? normalizeLocale(localeOverride) : currentLocale;
  const dict = DICTS[loc] || DICTS['zh-CN'];
  let raw = dict[key];
  if (raw === undefined) raw = DICTS['zh-CN'][key];
  if (raw === undefined) raw = String(key);
  if (!vars || typeof vars !== 'object') return raw;
  return raw.replace(/\{\{\s*([a-zA-Z0-9_.-]+)\s*\}\}/g, (match, name) => (
    Object.prototype.hasOwnProperty.call(vars, name) && vars[name] != null ? String(vars[name]) : match
  ));
}

export function useLocale() {
  return useSyncExternalStore(subscribeLocale, getLocale, getLocale);
}

export function useT() {
  const loc = useLocale();
  return useCallback((key, vars) => t(key, vars, loc), [loc]);
}
